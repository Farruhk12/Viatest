function setupProductInteractions() {
  document.addEventListener("click", (event) => {
    const detailButton = event.target.closest("[data-detail]");
    if (detailButton) {
      renderProductDetail(detailButton.dataset.detail);
      document.querySelector("#product-detail")?.scrollIntoView({ behavior: "smooth", block: "start" });
      return;
    }

    const buyLink = event.target.closest("[data-place]");
    if (buyLink && buyLink.matches("a")) {
      const place = buyLink.dataset.place;
      const productId = buyLink.dataset.productId || "default";
      trackEvent(eventNamesByPlace[place] || "buy_redirect", {
        product_id: productId,
        place
      });
      trackEvent("buy_redirect", {
        product_id: productId,
        place,
        url: buyLink.href
      });
    }

    const eventLink = event.target.closest("[data-event]");
    if (eventLink) {
      trackEvent(eventLink.dataset.event, {
        href: eventLink.getAttribute("href")
      });
    }
  });
}

