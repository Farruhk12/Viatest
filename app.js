let currentLanguage = getInitialLanguage();
const originalTextNodes = new WeakMap();
const originalAttributes = new WeakMap();

function getInitialLanguage() {
  try {
    const params = new URLSearchParams(window.location.search);
    const urlLanguage = params.get("lang");
    if (SUPPORTED_LANGUAGES.includes(urlLanguage)) return urlLanguage;

    const storedLanguage = window.localStorage?.getItem(LANGUAGE_STORAGE_KEY);
    if (SUPPORTED_LANGUAGES.includes(storedLanguage)) return storedLanguage;
  } catch (error) {
    return "ru";
  }

  return "ru";
}

function translateString(value, language = currentLanguage) {
  if (language !== "tj" || !value) return value;
  return tajikTranslations[value] || value;
}

function getOriginalAttribute(element, attribute) {
  let attributes = originalAttributes.get(element);
  if (!attributes) {
    attributes = {};
    originalAttributes.set(element, attributes);
  }

  if (!(attribute in attributes)) {
    attributes[attribute] = element.getAttribute(attribute) || "";
  }

  return attributes[attribute];
}

function translateAttributes(root = document) {
  const attributes = ["aria-label", "alt", "title", "placeholder"];
  const elements = root.querySelectorAll ? root.querySelectorAll("*") : [];

  elements.forEach((element) => {
    attributes.forEach((attribute) => {
      if (!element.hasAttribute(attribute)) return;
      const originalValue = getOriginalAttribute(element, attribute);
      element.setAttribute(attribute, translateString(originalValue));
    });
  });
}

function translateTextNodes(root = document.body) {
  if (!root) return;

  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
    acceptNode(node) {
      if (!node.nodeValue || !node.nodeValue.trim()) return NodeFilter.FILTER_REJECT;
      const parent = node.parentElement;
      if (!parent || parent.closest("script, style, noscript, svg")) return NodeFilter.FILTER_REJECT;
      return NodeFilter.FILTER_ACCEPT;
    }
  });
  const nodes = [];

  while (walker.nextNode()) {
    nodes.push(walker.currentNode);
  }

  nodes.forEach((node) => {
    if (!originalTextNodes.has(node)) {
      originalTextNodes.set(node, node.nodeValue);
    }

    const originalValue = originalTextNodes.get(node);
    const trimmedValue = originalValue.trim();
    const translatedValue = translateString(trimmedValue);
    node.nodeValue = translatedValue === trimmedValue ? originalValue : originalValue.replace(trimmedValue, translatedValue);
  });
}

function applyTranslations(root = document.body) {
  document.documentElement.lang = currentLanguage === "tj" ? "tg" : "ru";

  if (root) {
    translateTextNodes(root);
    translateAttributes(root);
  }

  if (document.title) {
    if (!document.documentElement.dataset.originalTitle) {
      document.documentElement.dataset.originalTitle = document.title;
    }
    document.title = translateString(document.documentElement.dataset.originalTitle);
  }

  document
    .querySelectorAll("meta[name='description'], meta[property='og:title'], meta[property='og:description']")
    .forEach((meta) => {
      const originalValue = getOriginalAttribute(meta, "content");
      meta.setAttribute("content", translateString(originalValue));
    });
}

function setTranslatedText(element, value) {
  if (!element) return;
  element.textContent = translateString(value);
  if (element.firstChild) {
    originalTextNodes.set(element.firstChild, value);
  }
}

function setTranslatedAttribute(element, attribute, value) {
  if (!element) return;
  let attributes = originalAttributes.get(element);
  if (!attributes) {
    attributes = {};
    originalAttributes.set(element, attributes);
  }
  attributes[attribute] = value;
  element.setAttribute(attribute, translateString(value));
}

